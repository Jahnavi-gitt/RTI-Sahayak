export function getLocalizedAuthority(record: DepartmentRecord, lang: Lang): Authority {
  const deptName = record.translations[lang] || record.officialName;
  const wing = record.wings[lang] || record.wings.en;
  return {
    id: record.id,
    name: deptName,
    department: wing && wing !== deptName ? `${wing} (${deptName})` : deptName,
    matchedFor: record.keywords,
    whyMatch: record.whyMatch[lang] || record.whyMatch.en
  };
}

export function getLocalizedDepartmentName(
  authOrRecord: Authority | DepartmentRecord | null | undefined,
  lang: Lang
): string {
  if (!authOrRecord) {
    const fallback = DEPARTMENTS_DATA[0];
    return fallback.translations[lang] || fallback.officialName;
  }
  if ("translations" in authOrRecord && authOrRecord.translations) {
    return authOrRecord.translations[lang] || authOrRecord.officialName;
  }
  const authName = "name" in authOrRecord ? authOrRecord.name : authOrRecord.officialName;
  const found = DEPARTMENTS_DATA.find(
    (d) => d.id === authOrRecord.id || d.officialName === authName || d.translations.en === authName
  );
  if (found) {
    return found.translations[lang] || found.officialName;
  }
  return authName;
}

